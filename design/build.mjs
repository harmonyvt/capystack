#!/usr/bin/env node
// Turns design/tokens.json into the two generated token files. Plain Node, no dependencies.
//
//   node design/build.mjs           write web/src/lib/design/tokens.css and
//                                   apple/Capystack/Design/Tokens.generated.swift
//   node design/build.mjs --check   write nothing; exit 1 when either file is missing or stale
//
// This script is the only writer of those two files. Never edit them by hand.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));
const CSS_OUT = "web/src/lib/design/tokens.css";
const SWIFT_OUT = "apple/Capystack/Design/Tokens.generated.swift";

const fail = (m) => { console.error(`design/build.mjs: ${m}`); process.exit(2); };
const HEX = /^#[0-9a-fA-F]{6}$/;
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const num = (n) => String(Number(n));

// ---- validate ----------------------------------------------------------------------------------
const colors = Object.entries(tokens.color);
for (const [name, v] of colors) {
  if (!HEX.test(v.light) || !HEX.test(v.dark)) fail(`color "${name}" needs light and dark as #rrggbb`);
}
const spaceKeys = Object.keys(tokens.space);
const weights = tokens.font.weight;
for (const [name, s] of Object.entries(tokens.font.size)) {
  if (!(s.weight in weights)) fail(`font size "${name}" uses unknown weight "${s.weight}"`);
}

// ---- CSS ---------------------------------------------------------------------------------------
function colorBlock(mode, indent) {
  return colors.map(([n, v]) => `${indent}--color-${n}: ${v[mode].toLowerCase()};`).join("\n");
}

function css() {
  const out = [];
  out.push("/* Generated by design/build.mjs from design/tokens.json. Do not edit by hand. */");
  out.push(":root {");
  out.push("  color-scheme: light dark;");
  out.push(colorBlock("light", "  "));
  out.push("");
  for (const k of spaceKeys) out.push(`  --space-${k}: ${tokens.space[k]}px;`);
  out.push("");
  for (const [k, v] of Object.entries(tokens.radius)) out.push(`  --radius-${k}: ${v}px;`);
  out.push("");
  out.push(`  --font-family: ${tokens.font.family};`);
  out.push(`  --font-family-mono: ${tokens.font.familyMono};`);
  for (const [k, v] of Object.entries(weights)) out.push(`  --font-weight-${k}: ${v};`);
  for (const [k, s] of Object.entries(tokens.font.size)) {
    out.push(`  --font-size-${k}: ${s.px}px;`);
    out.push(`  --font-weight-${k}: ${weights[s.weight]};`);
  }
  out.push("");
  out.push(`  --motion-fast: ${tokens.motion.fast}s;`);
  out.push(`  --motion-base: ${tokens.motion.base}s;`);
  out.push(`  --motion-slow: ${tokens.motion.slow}s;`);
  out.push(`  --motion-spring-response: ${tokens.motion.spring.response}s;`);
  out.push(`  --motion-spring-damping: ${tokens.motion.spring.damping};`);
  out.push("}");
  out.push("");
  out.push("@media (prefers-color-scheme: dark) {");
  out.push("  :root {");
  out.push(colorBlock("dark", "    "));
  out.push("  }");
  out.push("}");
  out.push("");
  out.push("/* Manual override (a settings toggle or a mockup): <html data-theme=\"light|dark\"> beats the system. */");
  for (const mode of ["light", "dark"]) {
    out.push(`:root[data-theme="${mode}"] {`);
    out.push(`  color-scheme: ${mode};`);
    out.push(colorBlock(mode, "  "));
    out.push("}");
  }
  out.push("");
  out.push("@media (prefers-reduced-motion: reduce) {");
  out.push("  :root {");
  out.push("    --motion-fast: 0.01s;");
  out.push("    --motion-base: 0.01s;");
  out.push("    --motion-slow: 0.01s;");
  out.push("  }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

// ---- Swift -------------------------------------------------------------------------------------
const hexInt = (h) => "0x" + h.slice(1).toUpperCase();
const swiftWeight = { regular: ".regular", medium: ".medium", semibold: ".semibold", bold: ".bold" };

function swift() {
  const o = [];
  o.push("// Generated by design/build.mjs from design/tokens.json. Do not edit by hand.");
  o.push("import SwiftUI");
  o.push("#if canImport(UIKit)");
  o.push("import UIKit");
  o.push("#elseif canImport(AppKit)");
  o.push("import AppKit");
  o.push("#endif");
  o.push("");
  o.push("enum Tokens {");
  o.push("    enum Color {");
  for (const [n, v] of colors) {
    o.push(`        static let ${camel(n)}: SwiftUI.Color = .dynamic(light: ${hexInt(v.light)}, dark: ${hexInt(v.dark)})`);
  }
  o.push("    }");
  o.push("");
  o.push("    enum Space {");
  for (const k of spaceKeys) o.push(`        static let s${k}: CGFloat = ${num(tokens.space[k])}`);
  o.push("    }");
  o.push("");
  o.push("    enum Radius {");
  for (const [k, v] of Object.entries(tokens.radius)) o.push(`        static let ${k}: CGFloat = ${num(v)}`);
  o.push("    }");
  o.push("");
  o.push("    enum Font {");
  for (const [k, s] of Object.entries(tokens.font.size)) {
    o.push(`        static let ${k}: SwiftUI.Font = .system(size: ${num(s.px)}, weight: ${swiftWeight[s.weight]}, design: .rounded)`);
  }
  o.push("    }");
  o.push("");
  o.push("    enum Motion {");
  o.push(`        static let fast: Double = ${num(tokens.motion.fast)}`);
  o.push(`        static let base: Double = ${num(tokens.motion.base)}`);
  o.push(`        static let slow: Double = ${num(tokens.motion.slow)}`);
  o.push(`        static let spring: Animation = .spring(response: ${num(tokens.motion.spring.response)}, dampingFraction: ${num(tokens.motion.spring.damping)})`);
  o.push("    }");
  o.push("}");
  o.push("");
  o.push("private extension SwiftUI.Color {");
  o.push("    /// A colour that follows the light or dark appearance of whatever draws it (iOS and macOS).");
  o.push("    static func dynamic(light: UInt32, dark: UInt32) -> SwiftUI.Color {");
  o.push("        #if canImport(UIKit)");
  o.push("        return SwiftUI.Color(uiColor: UIColor { traits in");
  o.push("            rgb(traits.userInterfaceStyle == .dark ? dark : light)");
  o.push("        })");
  o.push("        #else");
  o.push("        return SwiftUI.Color(nsColor: NSColor(name: nil) { appearance in");
  o.push("            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua");
  o.push("            return rgb(isDark ? dark : light)");
  o.push("        })");
  o.push("        #endif");
  o.push("    }");
  o.push("}");
  o.push("");
  o.push("#if canImport(UIKit)");
  o.push("private func rgb(_ hex: UInt32) -> UIColor {");
  o.push("    UIColor(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,");
  o.push("            blue: CGFloat(hex & 0xFF) / 255, alpha: 1)");
  o.push("}");
  o.push("#else");
  o.push("private func rgb(_ hex: UInt32) -> NSColor {");
  o.push("    NSColor(srgbRed: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,");
  o.push("            blue: CGFloat(hex & 0xFF) / 255, alpha: 1)");
  o.push("}");
  o.push("#endif");
  o.push("");
  return o.join("\n");
}

// ---- write or check ----------------------------------------------------------------------------
const outputs = [[CSS_OUT, css()], [SWIFT_OUT, swift()]];
const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, text] of outputs) {
  const file = join(root, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      console.error(`stale: ${rel} (run: node design/build.mjs)`);
      stale++;
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("design tokens are up to date");
}
